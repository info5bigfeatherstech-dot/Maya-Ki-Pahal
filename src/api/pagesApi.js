export function getPageContent(slug) {
  return new Promise((resolve, reject) => {
    window.setTimeout(() => {
      const page = pages[slug];
      if (!page) {
        reject(new Error(`No page content is configured for "${slug}".`));
        return;
      }
      resolve(page);
    }, 350);
  });
}